/** Russian plural: 1 трек, 2 трека, 5 треков (11–14 — like 5). */
function plural(n: number, one: string, few: string, many: string) {
  const a = Math.abs(n) % 100;
  const b = a % 10;
  if (a > 10 && a < 20) return many;
  if (b === 1) return one;
  if (b >= 2 && b <= 4) return few;
  return many;
}
/** "12 345" written by SoundCloud's numbers ("1,234") as a number again, for the plural */
const num = (s: string) => Number(s.replace(/[^\d]/g, "")) || 0;
const n = (count: number, one: string, few: string, many: string) => `${count} ${plural(count, one, few, many)}`;

